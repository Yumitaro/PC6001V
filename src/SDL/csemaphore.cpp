#include <SDL3/SDL.h>

#include "csemaphore.h"


/////////////////////////////////////////////////////////////////////////////
// Mutex クラス
/////////////////////////////////////////////////////////////////////////////

/////////////////////////////////////////////////////////////////////////////
// Constructor
/////////////////////////////////////////////////////////////////////////////
cMutex::cMutex( void )
{
	mtx = (HCRSECT)SDL_CreateMutex();
}


/////////////////////////////////////////////////////////////////////////////
// Destructor
/////////////////////////////////////////////////////////////////////////////
cMutex::~cMutex( void )
{
	SDL_DestroyMutex( (SDL_Mutex*)mtx );
}


/////////////////////////////////////////////////////////////////////////////
// Lock
/////////////////////////////////////////////////////////////////////////////
void cMutex::lock( void )
{
	if( mtx ){
		SDL_LockMutex( (SDL_Mutex*)mtx );
	}
}


/////////////////////////////////////////////////////////////////////////////
// Unlock
/////////////////////////////////////////////////////////////////////////////
void cMutex::unlock( void )
{
	if( mtx ){
		SDL_UnlockMutex( (SDL_Mutex*)mtx );
	}
}




