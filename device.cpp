////////////////////////////////////////////////////////////////
// デバイス追加
////////////////////////////////////////////////////////////////
bool DeviceList::Add( IDevice* t )
{
	ID id;
	Node n = { t, 0 };
	
	if( !t || !(id = t->GetID()) ) return false;
	
	auto p = NodeMap.emplace( id, std::move( n ) );
	// p.first  : 要素へのイテレータ
	// p.second : true:新規挿入された false:すでに存在する
	p.first->second.count++;
	return true;
}


////////////////////////////////////////////////////////////////
// デバイス削除
////////////////////////////////////////////////////////////////
bool DeviceList::Del( const ID id )
{
	try{
		Node& n = NodeMap.at( id );
		if( !--n.count ) NodeMap.erase( id );
		return true;
	}
	catch( std::out_of_range& ){
		return false;
	}
}


////////////////////////////////////////////////////////////////
// デバイス検索
////////////////////////////////////////////////////////////////
IDevice* DeviceList::Find( const ID id )
{
	try{
		Node& n = NodeMap.at( id );
		return n.entry;
	}
	catch( std::out_of_range& ){
		return nullptr;
	}
}
